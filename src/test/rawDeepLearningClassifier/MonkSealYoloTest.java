package test.rawDeepLearningClassifier;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.File;
import java.net.URI;
import java.net.URL;
import java.nio.file.Paths;
import java.util.ArrayList;

import org.jamdev.jdl4pam.utils.DLMatFile;
import org.jamdev.jpamutils.wavFiles.AudioData;
import org.jamdev.jdl4pam.utils.DLUtils;
import org.junit.jupiter.api.Test;

import rawDeepLearningClassifier.DLDownloadManager;
import rawDeepLearningClassifier.DLStatus;
import rawDeepLearningClassifier.dlClassification.genericModel.StandardPrediction;
import rawDeepLearningClassifier.dlClassification.yolo.YoloClassifier;
import rawDeepLearningClassifier.dlClassification.yolo.YoloParams;
import rawDeepLearningClassifier.dlClassification.yolo.YoloPrediction;
import rawDeepLearningClassifier.dlClassification.yolo.YoloWorker;
import rawDeepLearningClassifier.segmenter.GroupedRawData;
import us.hebi.matlab.mat.format.Mat5;
import us.hebi.matlab.mat.format.Mat5File;
import us.hebi.matlab.mat.types.Matrix;

/**
 * Test the Hawaiian monk seal call detector (Rasmussen, Sills, Parnell,
 * Reichmuth 2026). This is a MATLAB yolov4ObjectDetector which has been
 * exported to a PyTorch model and is run using the YOLO classifier.
 * <p>
 * The reference detections were generated by running the detection code from
 * the MATLAB app (BiggerBlueHMSdetector.mlapp) on a short clip of the demo file
 * (see make_monk_seal_reference.m in the resources folder). The model is too
 * large to keep in the repository and so is downloaded from the PAMGuard
 * deeplearningmodels repository.
 */
public class MonkSealYoloTest {

	private static final String RESOURCE_FOLDER = "./src/test/resources/rawDeepLearningClassifier/YOLO/monk_seal_hms/";

	/**
	 * The model on the PAMGuard deeplearningmodels GitHub repository.
	 */
	public static final String MODEL_URL = "https://github.com/PAMGuard/deeplearningmodels/releases/download/1.0/monk_seal_hms_yolov4.zip";

	/**
	 * The minimum intersection over union of a PAMGuard and MATLAB bounding box for them to be the same detection.
	 */
	private static final double MIN_IOU = 0.95;

	@Test
	public void monkSealTest() throws Exception {

		File modelFile = getModelFile();
		assertNotNull(modelFile, "Unable to download the monk seal model from " + MODEL_URL);

		String wavFilePath = Paths.get(RESOURCE_FOLDER + "monk_seal_hms_clip_20210513_003425.wav").toAbsolutePath().normalize().toString();
		String refPath = Paths.get(RESOURCE_FOLDER + "monk_seal_hms_matlab_detections.mat").toAbsolutePath().normalize().toString();

		//load the MATLAB reference detections
		Mat5File matFile = Mat5.readFromFile(refPath);
		double[] segStart = column(matFile.getMatrix("seg_start"));
		double[][] refBoxes = DLMatFile.matrix2array(matFile.getMatrix("det_bbox"));
		double[] refSegment = column(matFile.getMatrix("det_segment"));
		double[] refScore = column(matFile.getMatrix("det_score"));
		double[] refLabel = column(matFile.getMatrix("det_label"));
		double[] refAppStart = column(matFile.getMatrix("app_tstart"));

		//load the model
		YoloWorker yoloWorker = new YoloWorker();
		YoloParams params = new YoloParams();
		params.modelPath = modelFile.getAbsolutePath();

		DLStatus status = yoloWorker.prepModel(params, null);
		assertEquals(DLStatus.MODEL_LOAD_SUCCESS, status);
		assertEquals(6, params.numClasses);

		//the MATLAB defaults - a 0.5 threshold and no merging of boxes.
		YoloClassifier.setWorkerParams(yoloWorker, params);

		AudioData soundData = DLUtils.loadWavFile(wavFilePath);
		double[] soundDataD = soundData.getScaledSampleAmplitudes();

		int segSamples = (int) Math.round((params.defaultSegmentLen / 1000.) * soundData.sampleRate);
		assertEquals(60*48000, segSamples);

		//create the segments at the same positions as MATLAB, zero padding the last segment.
		ArrayList<GroupedRawData> groupedData = new ArrayList<GroupedRawData>();
		for (int i = 0; i < segStart.length; i++) {
			int startSample = (int) segStart[i];
			GroupedRawData groupedRawData = new GroupedRawData((long) (1000.*startSample/soundData.sampleRate), 1, startSample, segSamples, segSamples);
			groupedRawData.setUID(i);
			int nCopy = Math.min(segSamples, soundDataD.length - startSample);
			System.arraycopy(soundDataD, startSample, groupedRawData.getRawData()[0], 0, nCopy);
			groupedData.add(groupedRawData);
		}

		ArrayList<StandardPrediction> predictions = yoloWorker.runModel(groupedData, soundData.sampleRate, 0);
		assertNotNull(predictions);

		yoloWorker.closeModel();

		System.out.println(String.format("Monk seal: %d PAMGuard detections and %d MATLAB detections", predictions.size(), refBoxes.length));

		//match each MATLAB detection to a PAMGuard detection.
		int nMatch = 0;
		double maxScoreDiff = 0;
		double maxBoxDiff = 0;
		for (int i = 0; i < refBoxes.length; i++) {
			YoloPrediction bestMatch = null;
			double bestIoU = 0;
			for (StandardPrediction prediction : predictions) {
				YoloPrediction yoloPrediction = (YoloPrediction) prediction;
				if (yoloPrediction.getParentSegmentID() != (long) refSegment[i]) continue;
				if (argMax(yoloPrediction.getPredicitions()) != (int) refLabel[i] - 1) continue;
				double iou = iou(refBoxes[i], yoloPrediction.getBoundingBox());
				if (iou > bestIoU) {
					bestIoU = iou;
					bestMatch = yoloPrediction;
				}
			}

			if (bestMatch != null && bestIoU >= MIN_IOU) {
				nMatch++;
				maxScoreDiff = Math.max(maxScoreDiff, Math.abs(bestMatch.getConfidence() - refScore[i]));
				for (int j = 0; j < 4; j++) {
					maxBoxDiff = Math.max(maxBoxDiff, Math.abs(bestMatch.getBoundingBox()[j] - refBoxes[i][j]));
				}
				//the MATLAB app stretches the time axis by the ratio of the image width and the number of
				//spectrogram frames (2368/2341) so times differ by up to ~0.7 s.
				double startSeconds = (segStart[(int) refSegment[i]] + (bestMatch.getX() - 0.5) / 2368. * segSamples) / soundData.sampleRate;
				System.out.println(String.format("Detection %d: segment %d class %d score MATLAB %.4f PAMGuard %.4f start time MATLAB app %.2f s PAMGuard %.2f s IoU %.4f",
						i, (int) refSegment[i], (int) refLabel[i], refScore[i], bestMatch.getConfidence(), refAppStart[i], startSeconds, bestIoU));
			}
			else {
				System.out.println(String.format("Detection %d: segment %d class %d score %.4f - NO MATCH (best IoU %.3f)",
						i, (int) refSegment[i], (int) refLabel[i], refScore[i], bestIoU));
			}
		}

		System.out.println(String.format("Monk seal: %d of %d matched. Max score difference %.5f, max box difference %.3f pixels",
				nMatch, refBoxes.length, maxScoreDiff, maxBoxDiff));

		//all MATLAB detections should be found by PAMGuard with the same class, box and score.
		assertEquals(refBoxes.length, predictions.size());
		assertEquals(refBoxes.length, nMatch);
		assertTrue(maxScoreDiff < 0.01);
		assertTrue(maxBoxDiff < 1.0);
	}

	/**
	 * Get the monk seal model, downloading it if it has not already been
	 * downloaded.
	 *
	 * @return the model zip file or null if the model could not be downloaded.
	 */
	public static File getModelFile() throws Exception {
		DLDownloadManager downloadManager = new DLDownloadManager();
		URL url = new URL(MODEL_URL);
		String modelName = "monk_seal_hms_yolov4";

		if (!downloadManager.isModelDownloaded(url, modelName)) {
			System.out.println("Downloading the monk seal model from " + MODEL_URL);
			//the manager unzips the model and searches for the model file.
			URI uri = downloadManager.downloadModel(new URI(MODEL_URL), modelName, new String[] {modelName + ".pdtf"});
			if (uri == null) return null;
		}

		File modelFile = downloadManager.getModelDownloadedFile(url, modelName);
		return modelFile.exists() ? modelFile : null;
	}

	private static double[] column(Matrix matrix) {
		double[] arr = new double[matrix.getNumElements()];
		for (int i = 0; i < arr.length; i++) {
			arr[i] = matrix.getDouble(i);
		}
		return arr;
	}

	private static int argMax(float[] arr) {
		int index = 0;
		for (int i = 1; i < arr.length; i++) {
			if (arr[i] > arr[index]) index = i;
		}
		return index;
	}

	/**
	 * Intersection over union of two boxes [x, y, width, height].
	 */
	private static double iou(double[] box1, double[] box2) {
		double width = Math.min(box1[0] + box1[2], box2[0] + box2[2]) - Math.max(box1[0], box2[0]);
		double height = Math.min(box1[1] + box1[3], box2[1] + box2[3]) - Math.max(box1[1], box2[1]);
		if (width <= 0 || height <= 0) return 0;
		double intersect = width * height;
		return intersect / (box1[2] * box1[3] + box2[2] * box2[3] - intersect);
	}

}
